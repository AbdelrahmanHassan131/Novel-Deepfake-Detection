import os
import argparse
import sys
from PIL import Image

def parse_args():
    parser = argparse.ArgumentParser(description="Combine 3 graph images into a single horizontal image.")
    parser.add_argument('base_dir', help="Path to the base directory containing the model folders.")
    return parser.parse_args()

def combine_images_in_folder(folder_path):
    # Expect specific filenames generated previously
    images_to_find = ['graph_train.jpg', 'graph_accuracy.jpg', 'graph_ap.jpg']
    
    loaded_images = []
    for fname in images_to_find:
        fpath = os.path.join(folder_path, fname)
        if os.path.exists(fpath):
            try:
                img = Image.open(fpath)
                loaded_images.append(img)
            except Exception as e:
                print(f"Error opening image {fpath}: {e}")
        else:
            print(f"Warning: {fname} not found in {folder_path}")

    if not loaded_images:
        print(f"No images to combine in {folder_path}")
        return

    # Assuming all images are roughly same size/height since we generated them
    # We will stitch horizontally
    widths, heights = zip(*(i.size for i in loaded_images))
    
    total_width = sum(widths)
    max_height = max(heights)
    
    # Create new blank white image
    combined_img = Image.new('RGB', (total_width, max_height), (255, 255, 255))
    
    x_offset = 0
    for img in loaded_images:
        # Resize if height mismatches? 
        # If generated by same script, heights should be identical.
        # Just paste.
        combined_img.paste(img, (x_offset, 0))
        x_offset += img.width
        
    output_path = os.path.join(folder_path, "combined_overview.jpg")
    combined_img.save(output_path)
    print(f"Created combined image: {output_path}")

def main():
    args = parse_args()
    base_dir = args.base_dir
    
    if not os.path.isdir(base_dir):
        print(f"Error: Directory '{base_dir}' does not exist.")
        return

    # Scan subdirectories
    subdirs = [d for d in os.listdir(base_dir) if os.path.isdir(os.path.join(base_dir, d))]
    
    print(f"Scanning {len(subdirs)} folders in {base_dir}...")
    
    for folder in subdirs:
        folder_path = os.path.join(base_dir, folder)
        combine_images_in_folder(folder_path)

if __name__ == "__main__":
    try:
        main()
    except ImportError:
        print("Error: PIL (Pillow) library not found. Please install it using 'pip install Pillow' or 'conda install pillow'")
